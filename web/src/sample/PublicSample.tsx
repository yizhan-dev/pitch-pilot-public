import { useMemo, useRef, useState } from 'react';
import { Canvas, useFrame } from '@react-three/fiber';
import { OrbitControls } from '@react-three/drei';
import type { Mesh } from 'three';
import { makeClock, type Clock } from '../clock';
import { Pitch } from '../three/Pitch';
import { BootFrame } from '../three/BootFrame';
import { ProceduralStadium } from '../three/stadium/Procedural';
import { Players } from '../three/players/Styles';
import { makeLooks } from '../three/players/looks';
import { sampleBall, sampleJoints, SAMPLE_SECONDS } from './scene';
import './sample.css';

function Scene({ clock, update }: { clock: Clock; update: (t: number) => void }) {
  const joints = useMemo(sampleJoints, []);
  const looks = useMemo(() => makeLooks(22, 11, { hair: 1, number: 1, skin: 1 }), []);
  const ball = useRef<Mesh>(null), hide = useMemo(() => ({ current: -1 }), []);
  useFrame((_, dt) => {
    if (clock.playing) clock.t = (clock.t + Math.min(dt, 0.1)) % SAMPLE_SECONDS;
    const [x, y, z] = sampleBall(clock.t);
    ball.current?.position.set(x, z, y);
    update(clock.t);
  });
  return <>
    <color attach="background" args={['#05070b']} />
    <hemisphereLight args={['#d2ddff', '#172018', 1.1]} />
    <directionalLight position={[-20, 60, 30]} intensity={2} />
    <Pitch glow={0.15} />
    <ProceduralStadium cutaway shell="crystal" time={() => clock.t} events={[]} />
    <Players J={joints} clock={clock} style="toon" looks={looks} hide={hide} attacking="home" />
    <mesh ref={ball}><sphereGeometry args={[0.22, 16, 12]} /><meshStandardMaterial color="#fafafa" /></mesh>
    <OrbitControls target={[0, 0, 0]} minDistance={15} maxDistance={150} maxPolarAngle={Math.PI * 0.48} />
    <BootFrame />
  </>;
}

/** A source-verification scene using the app's own pitch, stadium and players.
 * The full production demo remains separate and contains licensed match clips.
 */
export function PublicSample() {
  const clock = useMemo(makeClock, []), [t, setT] = useState(0), [playing, setPlaying] = useState(false);
  const toggle = () => { clock.playing = !clock.playing; setPlaying(clock.playing); };
  return <main className="sample-shell">
    <header className="sample-header"><div><b>Pitch Pilot</b><span>Public source preview</span></div>
      <a href="https://pitch-pilot.projkick.com/" target="_blank" rel="noreferrer">Open the full demo ↗</a></header>
    <div className="sample-scene"><Canvas dpr={[1, 1.5]} camera={{ fov: 40, position: [5, 48, 70], far: 1500 }}>
      <Scene clock={clock} update={setT} />
    </Canvas></div>
    <aside className="sample-note"><span className="sample-label">SYNTHETIC FIXTURE</span>
      <h1>Same renderer. A hand-authored scene.</h1>
      <p>Drag to orbit and scroll to zoom. These positions and poses are generated by simple formulas.
        This preview contains no licensed match data or trained model weights.</p>
      <p>The full demo offers Watch, Explain, Tactics and What-if. This scene verifies the public renderer;
        it does not reproduce the private models or their predictions.</p></aside>
    <footer className="sample-controls"><button onClick={toggle}>{playing ? 'Pause' : 'Play'}</button>
      <button onClick={() => { clock.t = 0; setT(0); }}>Restart</button>
      <input aria-label="Preview time" type="range" min="0" max={SAMPLE_SECONDS} step="0.1" value={t}
        onChange={e => { clock.t = Number(e.target.value); setT(clock.t); }} />
      <output>{t.toFixed(1)} / {SAMPLE_SECONDS} s</output></footer>
  </main>;
}
